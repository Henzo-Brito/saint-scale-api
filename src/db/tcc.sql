BEGIN;

DROP TABLE IF EXISTS membros_escalas CASCADE;
DROP TABLE IF EXISTS membros CASCADE;
DROP TABLE IF EXISTS funcoes_avisos CASCADE;
DROP TABLE IF EXISTS musicas_escalas CASCADE;
DROP TABLE IF EXISTS escalas CASCADE;
DROP TABLE IF EXISTS avisos CASCADE;
DROP TABLE IF EXISTS funcoes CASCADE;
DROP TABLE IF EXISTS logradouro CASCADE;
DROP TABLE IF EXISTS musicas CASCADE;


CREATE TABLE IF NOT EXISTS musicas (
    ID_musica INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tom CHAR(4) DEFAULT NULL,
    nome VARCHAR(150) NOT NULL,
    autor VARCHAR(150) NOT NULL,
    link_spotify VARCHAR(255) DEFAULT NULL,
    link_youtube VARCHAR(255) DEFAULT NULL,
    link_cifra VARCHAR(255) DEFAULT NULL,
    link_letra VARCHAR(255) DEFAULT NULL,
    bpm CHAR(3) DEFAULT NULL,
    duracao CHAR(6) NOT NULL
);


CREATE TABLE IF NOT EXISTS logradouro (
    ID_logradouro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rua VARCHAR(500) NOT NULL,
    numero VARCHAR(10) NOT NULL,
    complemento VARCHAR(100),
    cidade VARCHAR(100) NOT NULL,
    estado VARCHAR(100) NOT NULL,
    cep VARCHAR(10) NOT NULL,
    ponto_referencia VARCHAR(255),
    status VARCHAR(10) DEFAULT 'ATIVO'
        CHECK (status IN ('ATIVO', 'INATIVO'))
);


CREATE TABLE IF NOT EXISTS funcoes (
    ID_funcao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    permissoes VARCHAR(255) NOT NULL
);


CREATE TABLE IF NOT EXISTS avisos (
    ID_avisos INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100),
    descrição VARCHAR(255),
    data_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ID_musica_FK INTEGER NOT NULL,

    FOREIGN KEY (ID_musica_FK)
        REFERENCES musicas(ID_musica)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS escalas (
    ID_escala INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    descrição VARCHAR(150),
    ID_musica_FK INTEGER NOT NULL,

    FOREIGN KEY (ID_musica_FK)
        REFERENCES musicas(ID_musica)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS musicas_escalas (
    ID_musica_escala INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tom CHAR(4) NOT NULL,
    descricao VARCHAR(100) NOT NULL,
    data_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ID_musica_FK INTEGER NOT NULL,
    ID_escala_FK INTEGER NOT NULL,

    FOREIGN KEY (ID_musica_FK)
        REFERENCES musicas(ID_musica)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (ID_escala_FK)
        REFERENCES escalas(ID_escala)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS funcoes_avisos (
    ID_funcoes_avisos INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_aviso_FK INTEGER NOT NULL,
    ID_funcao_FK INTEGER NOT NULL,

    FOREIGN KEY (ID_aviso_FK)
        REFERENCES avisos(ID_avisos)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (ID_funcao_FK)
        REFERENCES funcoes(ID_funcao)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS membros (
    ID_membro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150),
    data_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_nascimento TIMESTAMP NOT NULL,
    telefone BIGINT NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    cargo VARCHAR(60) NOT NULL,
    ID_funcao_FK INTEGER,
    ID_logradouro_FK INTEGER,

    FOREIGN KEY (ID_funcao_FK)
        REFERENCES funcoes(ID_funcao)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (ID_logradouro_FK)
        REFERENCES logradouro(ID_logradouro)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


CREATE TABLE IF NOT EXISTS membros_escalas (
    ID_membro_escala INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_membro CHAR(50) NOT NULL,
    data_registro TIMESTAMP NOT NULL,
    ID_escala_FK INTEGER NOT NULL,
    ID_membro_FK INTEGER NOT NULL,

    FOREIGN KEY (ID_escala_FK)
        REFERENCES escalas(ID_escala)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    FOREIGN KEY (ID_membro_FK)
        REFERENCES membros(ID_membro)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);


